//! 中文为源文案, 英文为对照. 缺译时回落到中文, 不露出内部 id.

use gpui::SharedString;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Language {
    Zh,
    En,
}

pub fn parse_language(code: &str) -> Language {
    if code.eq_ignore_ascii_case("en") {
        Language::En
    } else {
        Language::Zh
    }
}

pub fn language_code(lang: Language) -> &'static str {
    match lang {
        Language::Zh => "zh",
        Language::En => "en",
    }
}

pub fn t(id: &str) -> SharedString {
    let text = if super::language() == Language::En {
        en(id).or_else(|| zh(id))
    } else {
        zh(id)
    };
    match text {
        Some(text) => text.into(),
        None => id.to_string().into(),
    }
}

/// 已有中文句子的对照. 英文没有条目时仍显示中文.
pub fn t_src(zh_text: &str) -> SharedString {
    if super::language() == Language::En {
        if let Some(en) = src_en(zh_text) {
            return en.into();
        }
    }
    zh_text.to_string().into()
}

